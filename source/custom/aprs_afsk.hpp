class AfskWave final {
public:
    static constexpr unsigned SamplesPerSymbol=32;
    static constexpr unsigned SampleRate=38400;
    static constexpr uint16_t Silence=2048;

    // radio_level is the on-air tone selection used by OEM 0x08006380.
    // Keep phase between bits and DMA buffer fills.
    uint16_t sample(bool radio_level) {
        phase_+=radio_level?0x08000000u:0x0eaaaaabu;
        return afsk_sine[phase_>>24];
    }
private:
    uint32_t phase_=0;
};

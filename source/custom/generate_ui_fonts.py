"""Generate the compact UI glyph tables from installed Windows fonts.
Run with Pillow and pass --mono for the original JetBrains Mono Bold font.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont
p=argparse.ArgumentParser()
p.add_argument('--mono',required=True,type=Path)
p.add_argument('--sans',default='C:/Windows/Fonts/seguisb.ttf',type=Path)
p.add_argument('--output',default=str(Path(__file__).with_name('ui_font_data.hpp')),type=Path)
a=p.parse_args()
chars=list(range(32,127))+list(range(0x410,0x450))+[0x401,0x451,0x25c4,0x25ba,0x25b2,0x25bc,0x21ba,0x00b0,0x00b7]
out=['// Generated by generate_ui_fonts.py. Packed 2-bit coverage.','#pragma once',
     'namespace rt950::screen {','struct Glyph {uint16_t code,offset;uint8_t width,height,advance;int8_t left,top;};',
     'struct Font {const Glyph *glyphs;const uint8_t *pixels;unsigned count;unsigned em=0;};']
for name,size,path,charset in [('Sans13',13,a.sans,chars),('Sans11',11,a.sans,chars),
                             ('Mono11',11,a.mono,sorted(set(map(ord,'0123456789.- +NFMAMUSBOffnLowMidHighmWkDICSQLT')))),
                             *[('Mono'+str(n),n,a.mono,list(map(ord,'0123456789.-_ '+('RADTEL' if n==24 else '')))) for n in (12,15,24,25)]]:
    font=ImageFont.truetype(str(path),size)
    pixels=[];glyphs=[]
    for code in charset:
        c=chr(code)
        glyph_font=ImageFont.truetype('C:/Windows/Fonts/seguisym.ttf',size) if code==0x21ba else font
        left,top,right,bottom=glyph_font.getbbox(c)
        width=max(0,right-left);height=max(0,bottom-top)
        im=Image.new('L',(width,height))
        ImageDraw.Draw(im).text((-left,-top),c,font=glyph_font,fill=255)
        levels=[(v*3+127)//255 for v in im.getdata()]
        packed=[]
        for pos in range(0,len(levels),4):
            value=0
            for n,level in enumerate(levels[pos:pos+4]):value|=level<<(n*2)
            packed.append(value)
        glyphs.append((code,len(pixels),width,height,round(glyph_font.getlength(c)),left,top))
        pixels.extend(packed)
    out+=['inline constexpr uint8_t '+name+'Pixels[]={'+','.join(map(str,pixels))+'};',
          'inline constexpr Glyph '+name+'Glyphs[]={'+','.join('{'+','.join(map(str,g))+'}' for g in glyphs)+'};',
          'inline constexpr Font '+name+'={'+name+'Glyphs,'+name+'Pixels,sizeof '+name+'Glyphs/sizeof *'+name+'Glyphs};']
out += [
 'inline constexpr Font Sans10={Sans13Glyphs,Sans13Pixels,Sans13.count,10};',
 '}']
a.output.write_text('\n'.join(out)+'\n',encoding='utf-8')
print(a.output)
